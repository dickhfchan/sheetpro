//! Catalog parity: which catalog items are wired to a registered command / function.
//! Writes docs/parity.md and fails if live counts drop below the floors.

use anyhow::{Result, bail};
use sp_engine::catalog;
use std::collections::BTreeMap;
use std::fmt::Write as _;

/// Raise these when parity rises; never lower them.
pub const COMMAND_FLOOR: usize = 259;
pub const FUNCTION_FLOOR: usize = 496;

pub struct Parity {
    pub commands_live: usize,
    pub commands_total: usize,
    pub functions_live: usize,
    pub functions_total: usize,
    pub markdown: String,
}

pub fn compute() -> Parity {
    let reg = sp_engine::registry();
    let fns = sp_formula::function_names();
    let mut md =
        String::from("# Parity\n\nGenerated by `cargo xtask parity`. Do not edit by hand.\n\n");
    md.push_str("Parity measures *wiring* (a command or function with the catalog id exists), not behaviour. See `docs/roadmap.md` › Honest parity assessment and `docs/scorecard.md`.\n\n");

    // Commands grouped by ribbon tab (first segment of the location).
    let mut groups: BTreeMap<String, Vec<(&str, &str, bool)>> = BTreeMap::new();
    let mut live = 0;
    for item in catalog::commands() {
        let tab = item.loc.split(" › ").next().unwrap_or("Other").to_string();
        let is_live = reg.get(&item.id).is_some();
        live += usize::from(is_live);
        groups
            .entry(tab)
            .or_default()
            .push((&item.id, &item.label, is_live));
    }
    let total = catalog::commands().len();
    let mut fn_live = 0;
    let mut fn_total = 0;
    let mut fn_groups: Vec<(String, usize, usize, Vec<String>)> = Vec::new();
    for g in catalog::functions() {
        let l = g.names.iter().filter(|n| fns.contains(&n.as_str())).count();
        let missing: Vec<String> = g
            .names
            .iter()
            .filter(|n| !fns.contains(&n.as_str()))
            .cloned()
            .collect();
        fn_live += l;
        fn_total += g.names.len();
        fn_groups.push((g.category.clone(), l, g.names.len(), missing));
    }
    let pct = |a: usize, b: usize| {
        if b == 0 {
            0.0
        } else {
            a as f64 * 100.0 / b as f64
        }
    };
    let _ = writeln!(md, "| Surface | Live | Total | % |\n|---|---|---|---|");
    let _ = writeln!(
        md,
        "| Commands (ribbon + keyboard) | {live} | {total} | {:.1}% |",
        pct(live, total)
    );
    let _ = writeln!(
        md,
        "| Worksheet functions | {fn_live} | {fn_total} | {:.1}% |",
        pct(fn_live, fn_total)
    );
    let _ = writeln!(
        md,
        "| **All** | **{}** | **{}** | **{:.1}%** |\n",
        live + fn_live,
        total + fn_total,
        pct(live + fn_live, total + fn_total)
    );

    md.push_str("## Commands by tab\n\n| Tab | Live | Total | Missing |\n|---|---|---|---|\n");
    for (tab, items) in &groups {
        let l = items.iter().filter(|i| i.2).count();
        let missing: Vec<String> = items
            .iter()
            .filter(|i| !i.2)
            .map(|i| format!("`{}`", i.0))
            .collect();
        let _ = writeln!(
            md,
            "| {tab} | {l} | {} | {} |",
            items.len(),
            if missing.is_empty() {
                "—".into()
            } else {
                missing.join(" ")
            }
        );
    }
    md.push_str(
        "\n## Functions by category\n\n| Category | Live | Total | Missing |\n|---|---|---|---|\n",
    );
    for (cat, l, t, missing) in &fn_groups {
        let _ = writeln!(
            md,
            "| {cat} | {l} | {t} | {} |",
            if missing.is_empty() {
                "—".into()
            } else {
                missing.join(" ")
            }
        );
    }
    // Registered ids that the catalog does not know (typos, or catalog gaps).
    let extra: Vec<&str> = reg
        .all()
        .iter()
        .map(|c| c.id)
        .filter(|id| catalog::find(id).is_none())
        .collect();
    let extra_fns: Vec<&str> = fns
        .iter()
        .copied()
        .filter(|f| {
            !catalog::functions()
                .iter()
                .any(|g| g.names.iter().any(|n| n == f))
        })
        .collect();
    md.push_str("\n## Registered but not in catalog\n\n");
    if extra.is_empty() && extra_fns.is_empty() {
        md.push_str("None.\n");
    } else {
        for e in extra {
            let _ = writeln!(md, "- command `{e}`");
        }
        for e in extra_fns {
            let _ = writeln!(md, "- function `{e}`");
        }
    }
    Parity {
        commands_live: live,
        commands_total: total,
        functions_live: fn_live,
        functions_total: fn_total,
        markdown: md,
    }
}

pub fn run(check: bool) -> Result<()> {
    let p = compute();
    let path = crate::root().join("docs/parity.md");
    if check {
        let existing = std::fs::read_to_string(&path).unwrap_or_default();
        if existing != p.markdown {
            bail!("docs/parity.md is stale: run `cargo xtask parity` and commit it");
        }
    } else {
        std::fs::write(&path, &p.markdown)?;
    }
    println!(
        "parity: commands {}/{} ({:.1}%), functions {}/{} ({:.1}%)",
        p.commands_live,
        p.commands_total,
        p.commands_live as f64 * 100.0 / p.commands_total.max(1) as f64,
        p.functions_live,
        p.functions_total,
        p.functions_live as f64 * 100.0 / p.functions_total.max(1) as f64
    );
    if p.commands_live < COMMAND_FLOOR || p.functions_live < FUNCTION_FLOOR {
        bail!(
            "parity regressed below floor (commands {} < {COMMAND_FLOOR} or functions {} < {FUNCTION_FLOOR})",
            p.commands_live,
            p.functions_live
        );
    }
    Ok(())
}

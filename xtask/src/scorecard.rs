//! docs/scorecard.md: per-area checklists (scorecard/*.toml), oracle results
//! (scorecard/oracle.json), perf vs budget (perf/baseline.json), and settings nothing reads.
//! Deterministic (no wall clock), so `--check` can detect a stale file in CI.

use anyhow::{Result, bail};
use serde::Deserialize;
use std::fmt::Write as _;
use std::path::Path;

#[derive(Deserialize)]
struct Checklist {
    area: String,
    item: Vec<Item>,
}

#[derive(Deserialize)]
struct Item {
    name: String,
    status: String,
    #[serde(default)]
    note: String,
}

/// Fields of `struct <name>` in a Rust source file (simple scanner; fields are `pub x: T,`).
fn struct_fields(src: &str, name: &str) -> Vec<String> {
    let Some(start) = src.find(&format!("pub struct {name} {{")) else {
        return Vec::new();
    };
    let body = src.get(start..).unwrap_or("");
    let body = body
        .get(..body.find("\n}").unwrap_or(body.len()))
        .unwrap_or("");
    body.lines()
        .filter_map(|l| {
            l.trim()
                .strip_prefix("pub ")
                .and_then(|l| l.split_once(':'))
                .map(|(f, _)| f.trim().to_string())
        })
        .filter(|f| !f.contains(' ') && !f.is_empty() && !f.starts_with("struct"))
        .collect()
}

fn read_dir_text(dir: &Path) -> String {
    let mut out = String::new();
    if let Ok(rd) = std::fs::read_dir(dir) {
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                out.push_str(&read_dir_text(&p));
            } else if p.extension().is_some_and(|x| x == "rs") {
                out.push_str(&std::fs::read_to_string(&p).unwrap_or_default());
            }
        }
    }
    out
}

/// Fields read through a model accessor rather than directly (field, accessor call).
const ACCESSORS: &[(&str, &str)] = &[
    ("col_widths", "col_width("),
    ("hidden_cols", "col_width("),
    ("default_col_width", "col_width("),
    ("row_heights", "row_height("),
    ("hidden_rows", "row_height("),
    ("default_row_height", "row_height("),
    ("font_size_tenths", "font_size()"),
    ("cells", "cells_in("),
];

fn read_via_accessor(field: &str, consumers: &str) -> bool {
    ACCESSORS
        .iter()
        .any(|(f, call)| *f == field && consumers.contains(call))
}

/// Settings stored in the model/view state that no rendering or UI code reads.
fn dead_settings(root: &Path) -> Vec<String> {
    let engine =
        std::fs::read_to_string(root.join("crates/sp_engine/src/lib.rs")).unwrap_or_default();
    let style =
        std::fs::read_to_string(root.join("crates/sp_model/src/style.rs")).unwrap_or_default();
    let model =
        std::fs::read_to_string(root.join("crates/sp_model/src/lib.rs")).unwrap_or_default();
    let ui = read_dir_text(&root.join("crates/sp_ui/src"));
    let render = read_dir_text(&root.join("crates/sp_render/src"));
    let consumers = format!("{ui}\n{render}");
    let mut dead = Vec::new();
    for f in struct_fields(&engine, "ViewState") {
        if !consumers.contains(&format!("view.{f}")) {
            dead.push(format!("ViewState.{f}"));
        }
    }
    for f in struct_fields(&style, "Style") {
        if !consumers.contains(&format!(".{f}")) && !read_via_accessor(&f, &consumers) {
            dead.push(format!("Style.{f}"));
        }
    }
    for f in struct_fields(&model, "Sheet") {
        if !consumers.contains(&format!(".{f}")) && !read_via_accessor(&f, &consumers) {
            dead.push(format!("Sheet.{f}"));
        }
    }
    dead
}

pub fn generate() -> Result<String> {
    let root = crate::root();
    let mut md = String::from(
        "# Scorecard\n\nGenerated by `cargo xtask scorecard` from `scorecard/*.toml`, `scorecard/oracle.json` and `perf/baseline.json`. Do not edit by hand.\n\n",
    );

    // Parity headline.
    let p = crate::parity::compute();
    let _ = writeln!(
        md,
        "## Catalog parity (wiring)\n\nCommands {}/{} · Functions {}/{} (details: `docs/parity.md`)\n",
        p.commands_live, p.commands_total, p.functions_live, p.functions_total
    );

    // Oracles.
    md.push_str("## Oracle corpus (behaviour)\n\n");
    match std::fs::read_to_string(root.join("scorecard/oracle.json"))
        .ok()
        .and_then(|t| serde_json::from_str::<crate::corpus::OracleReport>(&t).ok())
    {
        Some(o) => {
            let f = crate::corpus::floors();
            let _ = writeln!(
                md,
                "Measured {} against IronCalc test files @ `{}`.\n",
                o.date,
                o.source_commit.get(..10).unwrap_or("")
            );
            let _ = writeln!(md, "| Metric | Result | Floor |\n|---|---|---|");
            let _ = writeln!(
                md,
                "| Formula test files fully matching | {}/{} | {} |",
                o.calc_files_pass, o.calc_files_total, f.calc_files_pass
            );
            let _ = writeln!(
                md,
                "| Formula cells matching cached results | {}/{} ({:.1}%) | {} |",
                o.cells_matched,
                o.cells_compared,
                o.cells_matched as f64 * 100.0 / o.cells_compared.max(1) as f64,
                f.cells_matched
            );
            let _ = writeln!(
                md,
                "| Files round-tripping through our writer | {}/{} | {} |\n",
                o.roundtrip_pass, o.files_total, f.roundtrip_pass
            );
            let mut worst: Vec<&crate::corpus::FileResult> = o
                .files
                .iter()
                .filter(|r| r.kind == "calc" && (r.matched < r.compared || r.load_error.is_some()))
                .collect();
            worst.sort_by_key(|r| std::cmp::Reverse(r.compared - r.matched));
            if !worst.is_empty() {
                md.push_str("Largest gaps (cells failing):\n\n| File | Matched | First mismatch |\n|---|---|---|\n");
                for r in worst.iter().take(25) {
                    let first = r
                        .load_error
                        .clone()
                        .or_else(|| r.first_mismatches.first().cloned())
                        .unwrap_or_default()
                        .replace('|', "\\|");
                    let _ = writeln!(
                        md,
                        "| `{}` | {}/{} | {} |",
                        r.path.trim_start_matches("xlsx/tests/"),
                        r.matched,
                        r.compared,
                        first.chars().take(120).collect::<String>()
                    );
                }
                md.push('\n');
            }
        }
        None => md
            .push_str("Not measured yet: run `cargo xtask corpus && cargo xtask test-corpus`.\n\n"),
    }

    // Perf.
    md.push_str("## Performance (100k rows)\n\n");
    match std::fs::read_to_string(root.join("perf/baseline.json"))
        .ok()
        .and_then(|t| serde_json::from_str::<crate::perf::Baseline>(&t).ok())
    {
        Some(b) => {
            let _ = writeln!(
                md,
                "Measured {} (release build).\n\n| Benchmark | Measured | Budget | Status | What |\n|---|---|---|---|---|",
                b.date
            );
            for (k, (ms, budget, desc)) in &b.results {
                let _ = writeln!(
                    md,
                    "| `{k}` | {ms:.1} ms | {budget:.0} ms | {} | {desc} |",
                    if ms <= budget { "ok" } else { "**OVER**" }
                );
            }
            md.push('\n');
        }
        None => md.push_str("Not measured yet: run `cargo xtask perf`.\n\n"),
    }

    // Checklists.
    md.push_str("## Area checklists\n\n");
    let mut files: Vec<_> = std::fs::read_dir(root.join("scorecard"))?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "toml") && !p.ends_with("floors.toml"))
        .collect();
    files.sort();
    let (mut done, mut partial, mut missing) = (0, 0, 0);
    let mut body = String::new();
    for f in files {
        let c: Checklist = toml::from_str(&std::fs::read_to_string(&f)?)?;
        let _ = writeln!(
            body,
            "### {}\n\n| Item | Status | Note |\n|---|---|---|",
            c.area
        );
        for i in &c.item {
            let icon = match i.status.as_str() {
                "done" => {
                    done += 1;
                    "✅ done"
                }
                "partial" => {
                    partial += 1;
                    "🟡 partial"
                }
                _ => {
                    missing += 1;
                    "⬜ missing"
                }
            };
            let _ = writeln!(
                body,
                "| {} | {icon} | {} |",
                i.name,
                i.note.replace('|', "\\|")
            );
        }
        body.push('\n');
    }
    let _ = writeln!(
        md,
        "Totals: {done} done · {partial} partial · {missing} missing\n"
    );
    md.push_str(&body);

    md.push_str("## Settings that nothing reads\n\nModel/view fields with no reader in `sp_render` or `sp_ui`: the setting can be changed but has no visible effect yet.\n\n");
    let dead = dead_settings(&root);
    if dead.is_empty() {
        md.push_str("None.\n");
    } else {
        for d in dead {
            let _ = writeln!(md, "- `{d}`");
        }
    }
    Ok(md)
}

pub fn run(check: bool) -> Result<()> {
    let md = generate()?;
    let path = crate::root().join("docs/scorecard.md");
    if check {
        if std::fs::read_to_string(&path).unwrap_or_default() != md {
            bail!("docs/scorecard.md is stale: run `cargo xtask scorecard` and commit it");
        }
        println!("scorecard: up to date");
    } else {
        std::fs::write(&path, md)?;
        println!("scorecard: wrote docs/scorecard.md");
    }
    Ok(())
}
